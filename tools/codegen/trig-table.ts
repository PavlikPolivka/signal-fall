// Generates packages/sim/src/trig-table.ts: integer lookup tables so the sim
// never calls Math.sin/atan at runtime. Run with `pnpm codegen:trig`.
// Angles are binary angles: ANGLE_FULL (4096) units per turn.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ONE = 1024;
const QUARTER = 1024; // ANGLE_FULL / 4
const ATAN_STEPS = 1024;

// sin for 0..QUARTER inclusive, scaled to Q10.
const sin = Array.from({ length: QUARTER + 1 }, (_, i) => Math.round(Math.sin((i / QUARTER) * (Math.PI / 2)) * ONE));
// atan(i / ATAN_STEPS) for i in 0..ATAN_STEPS, in binary angle units (0..512 = 0..45°).
const atan = Array.from({ length: ATAN_STEPS + 1 }, (_, i) => Math.round((Math.atan(i / ATAN_STEPS) / (2 * Math.PI)) * 4096));

const chunk = (xs: number[]) => {
  const lines: string[] = [];
  for (let i = 0; i < xs.length; i += 24) lines.push('  ' + xs.slice(i, i + 24).join(', ') + ',');
  return lines.join('\n');
};

const out = `// GENERATED by tools/codegen/trig-table.ts. Do not edit.
/** sin(i/1024 * 90°) in Q10, i = 0..1024 */
export const SIN_QUARTER: readonly number[] = [
${chunk(sin)}
];
/** atan(i/1024) in binary angle units (4096 per turn), i = 0..1024 */
export const ATAN_TABLE: readonly number[] = [
${chunk(atan)}
];
`;
const target = fileURLToPath(new URL('../../packages/sim/src/trig-table.ts', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${target}`);
